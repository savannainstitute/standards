"""Real local commits exercise adoption, upgrades, isolation, and rollback."""

import subprocess
from pathlib import Path

import pytest
import yaml
from yamllint import linter
from yamllint.config import YamlLintConfig

from standards import agent_files, release_bundle, shared_files


def git(root, *args):
    """Run Git in an isolated fixture repository."""
    return subprocess.run(
        [
            "git",
            "-C",
            str(root),
            "-c",
            "user.name=Test",
            "-c",
            "user.email=test@example.org",
            *args,
        ],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()


@pytest.fixture
def releases(tmp_path):
    """Create two real revisions with distinguishable agent instructions."""
    root = tmp_path / "standards"
    root.mkdir()
    source = Path(__file__).parents[1]
    paths = [
        "src/standards/configs/caller.yml",
        ".github/workflows/checks.yml",
        "templates/documentation-and-configuration/.pre-commit-config.yaml",
    ]
    paths.extend(f"src/standards/agent/{name}" for name in agent_files.COPIES)
    for path in paths:
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes((source / path).read_bytes())
    git(root, "init", "-q")
    git(root, "add", "-A")
    git(root, "commit", "-qm", "First release")
    first = git(root, "rev-parse", "HEAD")
    agent = root / "src/standards/agent/AGENTS.md"
    agent.write_text(
        "Release two.\n" + agent.read_text(encoding="utf-8"), encoding="utf-8"
    )
    git(root, "add", "-A")
    git(root, "commit", "-qm", "Second release")
    return root, first, git(root, "rev-parse", "HEAD")


def snapshot(repo):
    """Capture every generated byte for rollback comparison."""
    return {
        p.relative_to(repo).as_posix(): p.read_bytes()
        for p in repo.rglob("*")
        if p.is_file()
    }


def test_adoption_upgrade_and_complete_rollback(releases, tmp_path):
    """Restore the first bundle exactly, including project notes."""
    root, first, second = releases
    repo = tmp_path / "consumer"
    release_bundle.apply(repo, root, first)
    assert (
        shared_files.caller_revision(
            (repo / shared_files.CALLER_PATH).read_text()
        )
        == first
    )
    assert shared_files.pre_commit_rev(repo) == first
    agent = repo / "AGENTS.md"
    agent.write_text(
        agent.read_text(encoding="utf-8") + "\nProject instructions.\n",
        encoding="utf-8",
        newline="\n",
    )
    original = snapshot(repo)
    release_bundle.apply(repo, root, second)
    assert shared_files.pre_commit_rev(repo) == second
    assert agent.read_text(encoding="utf-8").startswith("Release two.")
    assert agent.read_text(encoding="utf-8").endswith(
        "Project instructions.\n"
    )
    release_bundle.apply(repo, root, first)
    assert snapshot(repo) == original


def test_later_central_commit_does_not_change_selected_bundle(
    releases, tmp_path
):
    """Installing the same old revision ignores newer central content."""
    root, first, _ = releases
    repo = tmp_path / "consumer"
    release_bundle.apply(repo, root, first)
    original = snapshot(repo)
    (root / "src/standards/agent/AGENTS.md").write_text("Unreleased change\n")
    git(root, "add", "-A")
    git(root, "commit", "-qm", "Later central change")
    release_bundle.apply(repo, root, first)
    assert snapshot(repo) == original


@pytest.mark.parametrize("bad", ["main", "a" * 40])
def test_invalid_release_leaves_existing_bundle_untouched(
    releases, tmp_path, bad
):
    """Reject moving or unavailable refs before writing any consumer file."""
    root, first, _ = releases
    repo = tmp_path / "consumer"
    release_bundle.apply(repo, root, first)
    original = snapshot(repo)
    with pytest.raises((ValueError, subprocess.CalledProcessError)):
        release_bundle.apply(repo, root, bad)
    assert snapshot(repo) == original


def test_adoption_preserves_other_hooks(releases, tmp_path):
    """A project hook survives a standards revision update."""
    root, first, second = releases
    repo = tmp_path / "consumer"
    release_bundle.apply(repo, root, first)
    path = repo / shared_files.PRE_COMMIT_PATH
    config = yaml.safe_load(path.read_text())
    external = {
        "repo": "local",
        "hooks": [{"id": "project-check", "entry": "check"}],
    }
    config["repos"].append(external)
    path.write_text(yaml.safe_dump(config))
    release_bundle.apply(repo, root, second)
    assert yaml.safe_load(path.read_text())["repos"][-1] == external


def test_hosted_check_rejects_running_another_release(tmp_path):
    """The caller and hooks must match the executing hosted revision."""
    shared_files.write_copies(tmp_path, "a" * 40)
    git(tmp_path, "init", "-q")
    git(tmp_path, "add", "-A")
    found = dict(shared_files.findings(tmp_path, "b" * 40))
    assert shared_files.CALLER_PATH in found
    assert shared_files.PRE_COMMIT_PATH in found


def test_adopted_yaml_passes_shared_lint(releases, tmp_path):
    """Generated caller and hooks pass the same YAML rules as hosted CI."""
    root, first, _ = releases
    repo = tmp_path / "consumer"
    release_bundle.apply(repo, root, first)
    config = YamlLintConfig(
        file=str(
            Path(__file__).parents[1] / "src/standards/configs/yamllint.yaml"
        )
    )
    for path in (shared_files.CALLER_PATH, shared_files.PRE_COMMIT_PATH):
        assert list(linter.run((repo / path).read_text(), config)) == []
